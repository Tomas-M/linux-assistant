#!/usr/bin/env python3
"""Update the untouched Codex submodule and verify the embedded integration."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.request

ROOT=Path(__file__).resolve().parents[1]
UPSTREAM=ROOT/"vendor/codex"


# Keep subprocess arguments structured on Windows and Unix.
def run(*args, cwd=ROOT, capture=False, env=None):
    return subprocess.run(args,cwd=cwd,check=True,text=True,encoding="utf-8",
                          stdout=subprocess.PIPE if capture else None,env=env).stdout


# Render only the dependency and environment forms the upstream manifests currently use.
def literal(value):
    if isinstance(value,dict):
        return "{ "+", ".join(f"{key} = {literal(item)}" for key,item in value.items())+" }"
    return json.dumps(value,ensure_ascii=False)


# Replace generated sections without rewriting unrelated application configuration.
def replace_section(text, name, content):
    pattern=rf"(?ms)^# BEGIN CODEX {name}[^\n]*\n.*?^# END CODEX {name}"
    result,count=re.subn(pattern,lambda _:f"# BEGIN CODEX {name} — generated by scripts/update_codex.py\n{content}\n# END CODEX {name}",text)
    if count!=1:
        raise ValueError(f"Expected one CODEX {name} section")
    return result


# Resolve a release, update pins, and run both ordinary and real-runtime integration tests.
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release",nargs="?",help="rust-vX.Y.Z, X.Y.Z, or latest")
    parser.add_argument("--check",action="store_true",help="Report the latest release without changing files")
    args=parser.parse_args()
    manifest=ROOT/"Cargo.toml"
    current=tomllib.loads(manifest.read_text(encoding="utf-8"))["workspace"]["metadata"]["codex"]["release"]
    if args.check or args.release=="latest":
        request=urllib.request.Request("https://api.github.com/repos/openai/codex/releases/latest",headers={"User-Agent":"linux-assistant-updater"})
        with urllib.request.urlopen(request,timeout=30) as response:
            latest=json.load(response)["tag_name"]
        if args.check:
            print(f"Pinned: {current}\nLatest: {latest}\n"+("Up to date." if current==latest else "An update is available."))
            return
        release=latest
    elif args.release:
        release=args.release if args.release.startswith("rust-v") else "rust-v"+args.release
    else:
        parser.error("Choose a release or use --check.")
    if not re.fullmatch(r"rust-v\d+\.\d+\.\d+",release):
        parser.error("Choose a stable rust-vX.Y.Z release.")
    if not (UPSTREAM/".git").exists():
        run("git","-c","core.longpaths=true","submodule","update","--init","--depth","1","--","vendor/codex")
    if run("git","status","--porcelain",cwd=UPSTREAM,capture=True).strip():
        raise RuntimeError("Codex source has local changes; preserve them before upgrading.")
    origin=run("git","remote","get-url","origin",cwd=UPSTREAM,capture=True).strip()
    if origin not in ("https://github.com/openai/codex","https://github.com/openai/codex.git"):
        raise RuntimeError("The Codex submodule must use the official openai/codex repository.")
    run("git","fetch","--depth","1","origin","tag",release,cwd=UPSTREAM)
    run("git","-c","core.longpaths=true","checkout","--detach","FETCH_HEAD",cwd=UPSTREAM)
    upstream=tomllib.loads((UPSTREAM/"codex-rs/Cargo.toml").read_text(encoding="utf-8"))
    if "rust-v"+upstream["workspace"]["package"]["version"]!=release:
        raise RuntimeError("Release tag and source version disagree.")
    patches=[]
    for source,packages in upstream.get("patch",{}).items():
        patches.append(f"[patch.{json.dumps(source)}]")
        for name,settings in packages.items():
            if "path" in settings:
                raise RuntimeError("An upstream path patch needs review before integration.")
            patches.append(f"{name} = {literal(settings)}")
        patches.append("")
    text=replace_section(manifest.read_text(encoding="utf-8"),"PATCHES","\n".join(patches).rstrip())
    text,count=re.subn(r'(?m)^(release = )"rust-v[^"]+"$',lambda m:m[1]+json.dumps(release),text)
    if count!=1:
        raise RuntimeError("Expected one upstream release pin.")
    manifest.write_text(text,encoding="utf-8")
    environment=tomllib.loads((UPSTREAM/"codex-rs/.cargo/config.toml").read_text(encoding="utf-8")).get("env",{})
    config=ROOT/".cargo/config.toml"
    env_text="[env]\n"+"\n".join(f"{key} = {literal(value)}" for key,value in environment.items())
    config.write_text(replace_section(config.read_text(encoding="utf-8"),"ENV",env_text),encoding="utf-8")
    channel=tomllib.loads((UPSTREAM/"codex-rs/rust-toolchain.toml").read_text(encoding="utf-8"))["toolchain"]["channel"]
    (ROOT/"rust-toolchain.toml").write_text(f'[toolchain]\nchannel = "{channel}"\nprofile = "minimal"\n',encoding="utf-8")
    # Seed the tested upstream dependency graph; Cargo adds our workspace's own packages.
    shutil.copyfile(UPSTREAM/"codex-rs/Cargo.lock",ROOT/"Cargo.lock")
    run("cargo","check","--workspace")
    run("cargo","build","-p","assistant-server","--bin","assistant-server","--example","provider-fixture","--locked")
    run("cargo","test","--workspace","--locked")
    metadata=json.loads(run("cargo","metadata","--format-version","1","--no-deps",capture=True))
    target=Path(metadata["target_directory"])/"debug"
    suffix=".exe" if sys.platform=="win32" else ""
    env=dict(os.environ,ASSISTANT_TEST_PROVIDER=str(target/"examples"/("provider-fixture"+suffix)),
             ASSISTANT_TEST_SERVER=str(target/("assistant-server"+suffix)))
    run("cargo","test","-p","assistant-server","integration_","--locked","--","--ignored",env=env)
    revision=run("git","rev-parse","HEAD",cwd=UPSTREAM,capture=True).strip()
    print(f"Verified {release} ({revision}). Review and commit the submodule pin, manifests, toolchain and Cargo.lock together.")


if __name__=="__main__":
    try:
        main()
    except (subprocess.CalledProcessError, OSError, ValueError, RuntimeError) as error:
        print(f"Codex update was not verified: {error}",file=sys.stderr)
        sys.exit(1)
